//! The Rust API types.

use crate::idl::*;
use std::fmt::Write;

pub fn rust_ty(ty: &Ty, idl: &Idl) -> String {
    match ty {
        Ty::Bool => "bool".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 => "u32".into(),
        Ty::U64 => "u64".into(),
        Ty::Str => "String".into(),
        Ty::Bytes => "Vec<u8>".into(),
        Ty::Named(n) if idl.is_interface(n) => "String".into(),
        Ty::Named(n) => n.clone(),
        Ty::Optional(t) => format!("Option<{}>", rust_ty(t, idl)),
        Ty::List(t) => format!("Vec<{}>", rust_ty(t, idl)),
    }
}

fn write_fields(out: &mut String, fields: &[Field], idl: &Idl, indent: &str, public: bool) {
    let vis = if public { "pub " } else { "" };
    for f in fields {
        let _ = writeln!(out, "{indent}/// {}", f.doc);
        match &f.ty {
            Ty::Bytes => {
                let _ = writeln!(out, "{indent}#[serde(with = \"crate::b64\")]");
            }
            Ty::Optional(inner) if **inner == Ty::Bytes => {
                let _ = writeln!(
                    out,
                    "{indent}#[serde(with = \"crate::b64_opt\", default, skip_serializing_if = \"Option::is_none\")]"
                );
            }
            Ty::Optional(_) => {
                let _ = writeln!(
                    out,
                    "{indent}#[serde(default, skip_serializing_if = \"Option::is_none\")]"
                );
            }
            _ => {}
        }
        let _ = writeln!(
            out,
            "{indent}{vis}{}: {},",
            snake(&f.name),
            rust_ty(&f.ty, idl)
        );
    }
}

pub fn generate(idl: &Idl) -> String {
    let mut out = String::new();
    out.push_str("// @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.\n\n");
    out.push_str("use serde::{Deserialize, Serialize};\n\n");
    let _ = writeln!(
        out,
        "/// The API version.\npub const API_VERSION: &str = {:?};",
        idl.api_version
    );
    let _ = writeln!(
        out,
        "/// The protocol version.\npub const PROTOCOL_VERSION: &str = {:?};\n",
        idl.protocol_version
    );

    out.push_str("/// Every error code.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[repr(u32)]\npub enum ErrorKind {\n");
    for e in &idl.errors {
        let _ = writeln!(
            out,
            "    /// {}\n    {} = {},",
            e.doc,
            upper_camel(&e.name),
            e.code
        );
    }
    out.push_str("}\n\nimpl ErrorKind {\n    /// The numeric code.\n    pub const fn code(self) -> u32 {\n        self as u32\n    }\n\n");
    out.push_str("    /// The IDL's name.\n    pub const fn name(self) -> &'static str {\n        match self {\n");
    for e in &idl.errors {
        let _ = writeln!(
            out,
            "            ErrorKind::{} => {:?},",
            upper_camel(&e.name),
            e.name
        );
    }
    out.push_str("        }\n    }\n\n    /// Finds the kind with this code.\n    pub const fn from_code(code: u32) -> Option<Self> {\n        match code {\n");
    for e in &idl.errors {
        let _ = writeln!(
            out,
            "            {} => Some(ErrorKind::{}),",
            e.code,
            upper_camel(&e.name)
        );
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n\n");

    for e in &idl.enums {
        let _ = writeln!(
            out,
            "/// {}\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = \"camelCase\")]\npub enum {} {{",
            e.doc, e.name
        );
        for (name, doc) in &e.values {
            let _ = writeln!(out, "    /// {doc}\n    {},", upper_camel(name));
        }
        out.push_str("}\n\n");
    }

    for r in &idl.records {
        let _ = writeln!(
            out,
            "/// {}\n#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = \"camelCase\")]\npub struct {} {{",
            r.doc, r.name
        );
        write_fields(&mut out, &r.fields, idl, "    ", true);
        out.push_str("}\n\n");
    }

    for v in &idl.variants {
        let _ = writeln!(
            out,
            "/// {}\n#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(tag = \"type\", rename_all = \"camelCase\", rename_all_fields = \"camelCase\")]\npub enum {} {{",
            v.doc, v.name
        );
        for c in &v.cases {
            let _ = writeln!(out, "    /// {}\n    {} {{", c.doc, upper_camel(&c.name));
            write_fields(&mut out, &c.fields, idl, "        ", false);
            out.push_str("    },\n");
        }
        out.push_str("}\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
