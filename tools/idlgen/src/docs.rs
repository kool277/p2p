//! `docs/SDK-API.md`, rendered from the IDL.

use crate::idl::*;
use std::fmt::Write;

fn ty_cell(ty: &Ty) -> String {
    format!("`{}`", ty.source())
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

fn write_fields(out: &mut String, fields: &[Field]) {
    if fields.is_empty() {
        return;
    }
    out.push_str("| Field | Type | Meaning |\n| --- | --- | --- |\n");
    for f in fields {
        let _ = writeln!(out, "| `{}` | {} | {} |", f.name, ty_cell(&f.ty), cell(&f.doc));
    }
    out.push('\n');
}

fn write_callable(out: &mut String, c: &Callable, heading: &str) {
    let params: Vec<String> = c.params.iter().map(|p| format!("{}: {}", p.name, p.ty.source())).collect();
    let returns = c.returns.as_ref().map_or_else(String::new, |r| format!(" -> {}", r.source()));
    let _ = writeln!(out, "{heading} `{}`\n", c.name);
    let _ = writeln!(out, "```\n{}{}({}){}\n```\n", if c.is_async { "async " } else { "" }, c.name, params.join(", "), returns);
    let _ = writeln!(out, "{}\n", c.doc);
    if !c.params.is_empty() {
        out.push_str("| Parameter | Type | Meaning |\n| --- | --- | --- |\n");
        for p in &c.params {
            let _ = writeln!(out, "| `{}` | {} | {} |", p.name, ty_cell(&p.ty), cell(&p.doc));
        }
        out.push('\n');
    }
    if !c.errors.is_empty() {
        let names: Vec<String> = c.errors.iter().map(|e| format!("`{e}`")).collect();
        let _ = writeln!(out, "Errors: {}.\n", names.join(", "));
    }
}

pub fn generate(idl: &Idl) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# SDK API\n\n<!-- @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit. -->\n");
    let _ = writeln!(out, "API version {}, protocol version {}.\n", idl.api_version, idl.protocol_version);
    out.push_str("This is the public API, the same in every language and over the sidecar. Only the casing changes to fit each language. `async` calls do network I/O, and each binding exposes them in its own idiom. Keys never appear here: only handles and public fingerprints do.\n\n");
    out.push_str("Every path carries these names and codes unchanged. Over JSON (the sidecar, and the structured values in the C ABI and WebAssembly), names are lowerCamelCase, `bytes` are standard base64, an enum is its name as a string, and a variant is an object whose `type` field is the case's name.\n\n");
    out.push_str("## Additions to the build prompt's list\n\nThe prompt names `connect`, `openChannel`, `send`, `receive`, `verifyPeer`, `rotateKeys` and `exportAudit`. Those alone cannot run a session.\n\n| Addition | Why it is needed |\n| --- | --- |\n");
    let additions = [
        ("enrollDevice", "A device needs a certificate before it can connect."),
        ("acceptChannel, rejectChannel", "The other side of openChannel."),
        ("nextEvent", "Events are polled, because callbacks across FFI are restricted."),
        ("close", "An authenticated close, so truncation can be detected."),
        ("info", "Shows the peer, path and key epoch."),
        ("createExternalTransport, ExternalTransport", "Browsers and mobile WebRTC own their sockets."),
        ("createServerCore, ServerCore", "The Host SPI, which the design describes in prose."),
        ("conformanceRun", "Lets each binding run the shared vectors in its own runtime."),
    ];
    for (name, why) in additions {
        let _ = writeln!(out, "| `{name}` | {why} |");
    }
    out.push('\n');

    out.push_str("## Error codes\n\n| Code | Name | Meaning |\n| --- | --- | --- |\n");
    for e in &idl.errors {
        let _ = writeln!(out, "| {} | `{}` | {} |", e.code, e.name, cell(&e.doc));
    }
    out.push_str("\n## Functions\n\n");
    for f in &idl.functions {
        write_callable(&mut out, f, "###");
    }
    out.push_str("## Interfaces\n\n");
    for i in &idl.interfaces {
        let _ = writeln!(out, "### `{}`\n\n{}\n", i.name, i.doc);
        for m in &i.methods {
            write_callable(&mut out, m, "####");
        }
    }
    out.push_str("## Records\n\n");
    for r in &idl.records {
        let _ = writeln!(out, "### `{}`\n\n{}\n", r.name, r.doc);
        write_fields(&mut out, &r.fields);
    }
    out.push_str("## Variants\n\n");
    for v in &idl.variants {
        let _ = writeln!(out, "### `{}`\n\n{}\n", v.name, v.doc);
        for c in &v.cases {
            let _ = writeln!(out, "#### `{}`\n\n{}\n", c.name, c.doc);
            write_fields(&mut out, &c.fields);
        }
    }
    out.push_str("## Enums\n\n");
    for e in &idl.enums {
        let _ = writeln!(out, "### `{}`\n\n{}\n\n| Value | Meaning |\n| --- | --- |", e.name, e.doc);
        for (name, doc) in &e.values {
            let _ = writeln!(out, "| `{name}` | {} |", cell(doc));
        }
        out.push('\n');
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
