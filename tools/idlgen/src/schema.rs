//! The language-neutral schemas: UniFFI `.udl`, WIT, JSON-RPC and TypeScript.

use crate::idl::*;
use serde_json::{Value, json};
use std::fmt::Write;

// ------------------------------------------------------------------- UniFFI .udl

fn udl_ty(ty: &Ty) -> String {
    match ty {
        Ty::Bool => "boolean".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 => "u32".into(),
        Ty::U64 => "u64".into(),
        Ty::Str => "string".into(),
        Ty::Bytes => "bytes".into(),
        Ty::Named(n) => n.clone(),
        Ty::Optional(t) => format!("{}?", udl_ty(t)),
        Ty::List(t) => format!("sequence<{}>", udl_ty(t)),
    }
}

fn udl_signature(c: &Callable, indent: &str, out: &mut String) {
    let params: Vec<String> = c.params.iter().map(|p| format!("{} {}", udl_ty(&p.ty), snake(&p.name))).collect();
    let returns = c.returns.as_ref().map_or_else(|| "void".to_string(), udl_ty);
    let mut attrs = vec![];
    if !c.errors.is_empty() {
        attrs.push("Throws=QalqonError".to_string());
    }
    if c.is_async {
        attrs.push("Async".to_string());
    }
    let attr = if attrs.is_empty() { String::new() } else { format!("[{}]\n{indent}", attrs.join(", ")) };
    let _ = writeln!(out, "{indent}{attr}{returns} {}({});", snake(&c.name), params.join(", "));
}

pub fn udl(idl: &Idl) -> String {
    let mut out = String::from("// @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.\n\nnamespace qalqon {\n");
    for f in &idl.functions {
        udl_signature(f, "  ", &mut out);
    }
    out.push_str("};\n\n[Error]\nenum QalqonError {\n");
    for e in idl.errors.iter().filter(|e| e.code != 0) {
        let _ = writeln!(out, "  \"{}\",", upper_camel(&e.name));
    }
    out.push_str("};\n");
    for e in &idl.enums {
        let _ = writeln!(out, "\nenum {} {{", e.name);
        for (name, _) in &e.values {
            let _ = writeln!(out, "  \"{name}\",");
        }
        out.push_str("};\n");
    }
    for r in &idl.records {
        let _ = writeln!(out, "\ndictionary {} {{", r.name);
        for f in &r.fields {
            let _ = writeln!(out, "  {} {};", udl_ty(&f.ty), snake(&f.name));
        }
        out.push_str("};\n");
    }
    for v in &idl.variants {
        let _ = writeln!(out, "\n[Enum]\ninterface {} {{", v.name);
        for c in &v.cases {
            let fields: Vec<String> = c.fields.iter().map(|f| format!("{} {}", udl_ty(&f.ty), snake(&f.name))).collect();
            let _ = writeln!(out, "  {}({});", upper_camel(&c.name), fields.join(", "));
        }
        out.push_str("};\n");
    }
    for i in &idl.interfaces {
        let _ = writeln!(out, "\ninterface {} {{", i.name);
        for m in &i.methods {
            udl_signature(m, "  ", &mut out);
        }
        out.push_str("};\n");
    }
    out
}

// ------------------------------------------------------------------------ WIT

fn kebab(name: &str) -> String {
    snake(name).replace('_', "-")
}

fn wit_ident(name: &str) -> String {
    let k = kebab(name);
    // WIT keywords are written with a leading %.
    if matches!(k.as_str(), "list" | "get" | "put" | "close" | "send" | "record" | "enum" | "variant" | "result" | "option" | "stream" | "type" | "use" | "from" | "with" | "func" | "resource" | "static") {
        format!("%{k}")
    } else {
        k
    }
}

fn wit_ty(ty: &Ty) -> String {
    match ty {
        Ty::Bool => "bool".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 => "u32".into(),
        Ty::U64 => "u64".into(),
        Ty::Str => "string".into(),
        Ty::Bytes => "list<u8>".into(),
        Ty::Named(n) => kebab(n),
        Ty::Optional(t) => format!("option<{}>", wit_ty(t)),
        Ty::List(t) => format!("list<{}>", wit_ty(t)),
    }
}

fn wit_func(c: &Callable, out: &mut String, indent: &str, owned: &dyn Fn(&Ty) -> String) {
    let params: Vec<String> = c.params.iter().map(|p| format!("{}: {}", wit_ident(&p.name), wit_ty(&p.ty))).collect();
    let ok = c.returns.as_ref().map(owned);
    let result = match (ok, c.errors.is_empty()) {
        (Some(t), true) => format!(" -> {t}"),
        (None, true) => String::new(),
        (Some(t), false) => format!(" -> result<{t}, error-code>"),
        (None, false) => " -> result<_, error-code>".to_string(),
    };
    let _ = writeln!(out, "{indent}{}: func({}){result};", wit_ident(&c.name), params.join(", "));
}

pub fn wit(idl: &Idl) -> String {
    let mut out = String::from("// @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.\npackage qalqon:api@0.1.0;\n\ninterface api {\n");
    out.push_str("  enum error-code {\n");
    for e in idl.errors.iter().filter(|e| e.code != 0) {
        let _ = writeln!(out, "    {},", wit_ident(&e.name));
    }
    out.push_str("  }\n\n");
    for e in &idl.enums {
        let _ = writeln!(out, "  enum {} {{", kebab(&e.name));
        for (name, _) in &e.values {
            let _ = writeln!(out, "    {},", wit_ident(name));
        }
        out.push_str("  }\n\n");
    }
    for r in &idl.records {
        let _ = writeln!(out, "  record {} {{", kebab(&r.name));
        for f in &r.fields {
            let _ = writeln!(out, "    {}: {},", wit_ident(&f.name), wit_ty(&f.ty));
        }
        out.push_str("  }\n\n");
    }
    for v in &idl.variants {
        for c in &v.cases {
            if !c.fields.is_empty() {
                let _ = writeln!(out, "  record {}-{} {{", kebab(&v.name), kebab(&c.name));
                for f in &c.fields {
                    let _ = writeln!(out, "    {}: {},", wit_ident(&f.name), wit_ty(&f.ty));
                }
                out.push_str("  }\n\n");
            }
        }
        let _ = writeln!(out, "  variant {} {{", kebab(&v.name));
        for c in &v.cases {
            if c.fields.is_empty() {
                let _ = writeln!(out, "    {},", wit_ident(&c.name));
            } else {
                let _ = writeln!(out, "    {}({}-{}),", wit_ident(&c.name), kebab(&v.name), kebab(&c.name));
            }
        }
        out.push_str("  }\n\n");
    }
    for i in &idl.interfaces {
        let _ = writeln!(out, "  resource {} {{", kebab(&i.name));
        for m in &i.methods {
            wit_func(m, &mut out, "    ", &wit_ty);
        }
        out.push_str("  }\n\n");
    }
    for f in &idl.functions {
        wit_func(f, &mut out, "  ", &wit_ty);
    }
    out.push_str("}\n\nworld qalqon {\n  export api;\n}\n");
    out
}

// ------------------------------------------------------------------- JSON-RPC

fn json_schema(ty: &Ty, idl: &Idl) -> Value {
    match ty {
        Ty::Bool => json!({ "type": "boolean" }),
        Ty::U16 => json!({ "type": "integer", "minimum": 0, "maximum": 65535 }),
        Ty::U32 => json!({ "type": "integer", "minimum": 0, "maximum": 4294967295u64 }),
        Ty::U64 => json!({ "type": "integer", "minimum": 0 }),
        Ty::Str => json!({ "type": "string" }),
        Ty::Bytes => json!({ "type": "string", "contentEncoding": "base64" }),
        Ty::Named(n) if idl.is_interface(n) => json!({ "type": "string", "description": format!("A handle to a {n}.") }),
        Ty::Named(n) => json!({ "$ref": format!("#/definitions/{n}") }),
        Ty::Optional(t) => json!({ "anyOf": [json_schema(t, idl), { "type": "null" }] }),
        Ty::List(t) => json!({ "type": "array", "items": json_schema(t, idl) }),
    }
}

fn object_schema(fields: &[Field], idl: &Idl, extra: Option<(&str, &str)>) -> Value {
    let mut properties = serde_json::Map::new();
    let mut required = Vec::new();
    if let Some((name, value)) = extra {
        properties.insert(name.into(), json!({ "const": value }));
        required.push(name.to_string());
    }
    for f in fields {
        let mut schema = json_schema(&f.ty, idl);
        if let Some(object) = schema.as_object_mut() {
            object.insert("description".into(), json!(f.doc));
        }
        properties.insert(f.name.clone(), schema);
        if !matches!(f.ty, Ty::Optional(_)) {
            required.push(f.name.clone());
        }
    }
    json!({ "type": "object", "properties": properties, "required": required, "additionalProperties": false })
}

fn method_entry(c: &Callable, idl: &Idl, prefix: Option<&str>) -> Value {
    let name = match prefix {
        Some(p) => format!("{}.{}", lower_camel(p), c.name),
        None => c.name.clone(),
    };
    let mut params = c.params.clone();
    if prefix.is_some() {
        params.insert(0, Field { name: "handle".into(), ty: Ty::Str, doc: "The object this call is on.".into() });
    }
    json!({
        "name": name,
        "description": c.doc,
        "async": c.is_async,
        "params": object_schema(&params, idl, None),
        "result": c.returns.as_ref().map_or(json!({ "type": "null" }), |r| json_schema(r, idl)),
        "errors": c.errors,
    })
}

pub fn jsonrpc(idl: &Idl) -> String {
    let mut definitions = serde_json::Map::new();
    for e in &idl.enums {
        let values: Vec<&String> = e.values.iter().map(|(n, _)| n).collect();
        definitions.insert(e.name.clone(), json!({ "description": e.doc, "enum": values }));
    }
    for r in &idl.records {
        let mut schema = object_schema(&r.fields, idl, None);
        schema["description"] = json!(r.doc);
        definitions.insert(r.name.clone(), schema);
    }
    for v in &idl.variants {
        let cases: Vec<Value> = v.cases.iter().map(|c| object_schema(&c.fields, idl, Some(("type", &c.name)))).collect();
        definitions.insert(v.name.clone(), json!({ "description": v.doc, "oneOf": cases }));
    }
    let mut methods: Vec<Value> = idl.functions.iter().map(|f| method_entry(f, idl, None)).collect();
    for i in &idl.interfaces {
        methods.extend(i.methods.iter().map(|m| method_entry(m, idl, Some(&i.name))));
    }
    let errors: Vec<Value> = idl.errors.iter().map(|e| json!({ "code": e.code, "name": e.name, "description": e.doc })).collect();
    let document = json!({
        "$comment": "@generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.",
        "api_version": idl.api_version,
        "protocol_version": idl.protocol_version,
        "errors": errors,
        "methods": methods,
        "definitions": definitions,
    });
    serde_json::to_string_pretty(&document).expect("the schema serialises") + "\n"
}

// ----------------------------------------------------------------- TypeScript

fn ts_ty(ty: &Ty, idl: &Idl) -> String {
    match ty {
        Ty::Bool => "boolean".into(),
        Ty::U16 | Ty::U32 | Ty::U64 => "number".into(),
        Ty::Str => "string".into(),
        Ty::Bytes => "Uint8Array".into(),
        Ty::Named(n) if idl.is_interface(n) => "string".into(),
        Ty::Named(n) => n.clone(),
        Ty::Optional(t) => format!("{} | null", ts_ty(t, idl)),
        Ty::List(t) => format!("Array<{}>", ts_ty(t, idl)),
    }
}

fn ts_fields(fields: &[Field], idl: &Idl, out: &mut String) {
    for f in fields {
        let optional = if matches!(f.ty, Ty::Optional(_)) { "?" } else { "" };
        let _ = writeln!(out, "  /** {} */\n  {}{optional}: {};", f.doc, f.name, ts_ty(&f.ty, idl));
    }
}

pub fn typescript(idl: &Idl) -> String {
    let mut out = String::from("// @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.\n\n");
    out.push_str("export const ErrorCode = {\n");
    for e in &idl.errors {
        let _ = writeln!(out, "  {}: {},", e.name, e.code);
    }
    out.push_str("} as const;\nexport type ErrorName = keyof typeof ErrorCode;\n\n");
    for e in &idl.enums {
        let names: Vec<String> = e.values.iter().map(|(n, _)| format!("{n:?}")).collect();
        let _ = writeln!(out, "/** {} */\nexport type {} = {};\n", e.doc, e.name, names.join(" | "));
    }
    for r in &idl.records {
        let _ = writeln!(out, "/** {} */\nexport interface {} {{", r.doc, r.name);
        ts_fields(&r.fields, idl, &mut out);
        out.push_str("}\n\n");
    }
    for v in &idl.variants {
        let _ = writeln!(out, "/** {} */\nexport type {} =", v.doc, v.name);
        for c in &v.cases {
            let _ = writeln!(out, "  | {{ type: {:?};", c.name);
            for f in &c.fields {
                let optional = if matches!(f.ty, Ty::Optional(_)) { "?" } else { "" };
                let _ = writeln!(out, "      {}{optional}: {};", f.name, ts_ty(&f.ty, idl));
            }
            out.push_str("    }\n");
        }
        out.push_str(";\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
