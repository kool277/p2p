//! The sidecar's dispatch table and its generated client libraries (ADR-0004).

use crate::c_abi::api_ty;
use crate::idl::*;
use std::fmt::Write;

fn method_name(c: &Callable, interface: Option<&InterfaceDef>) -> String {
    match interface {
        Some(i) => format!("{}.{}", lower_camel(&i.name), c.name),
        None => c.name.clone(),
    }
}

fn dispatch_arm(out: &mut String, c: &Callable, interface: Option<&InterfaceDef>, idl: &Idl) {
    let _ = writeln!(out, "        {:?} => {{", method_name(c, interface));
    if let Some(i) = interface {
        let _ = writeln!(out, "            let object = state.{}(params)?;", snake(&i.name));
    }
    for p in &c.params {
        let name = snake(&p.name);
        let line = match &p.ty {
            Ty::Str => format!("            let {name} = text_arg(params, {:?})?;\n", p.name),
            Ty::Bytes => format!("            let {name} = bytes_arg(params, {:?})?;\n", p.name),
            Ty::Optional(t) if **t == Ty::Bytes => format!("            let {name} = optional_bytes_arg(params, {:?})?;\n", p.name),
            t => format!("            let {name}: {} = arg(params, {:?})?;\n", api_ty(t), p.name),
        };
        out.push_str(&line);
    }
    let args: Vec<String> = c
        .params
        .iter()
        .map(|p| {
            let name = snake(&p.name);
            match &p.ty {
                Ty::Str => format!("&{name}"),
                Ty::Bytes => format!("&{name}"),
                _ => name,
            }
        })
        .collect();
    let call = match interface {
        Some(_) => format!("object.{}({})", snake(&c.name), args.join(", ")),
        None => format!("qalqon_sdk::{}({})", snake(&c.name), args.join(", ")),
    };
    let body = match &c.returns {
        None => format!("            {call}?;\n            Ok(Value::Null)\n"),
        Some(Ty::Named(n)) if idl.is_interface(n) => {
            format!("            let result = {call}?;\n            Ok(state.add_{}(result))\n", snake(n))
        }
        Some(Ty::Bytes) => format!("            Ok(Value::String(api::b64::encode(&{call}?)))\n"),
        Some(Ty::Optional(t)) if **t == Ty::Bytes => {
            format!("            Ok({call}?.map_or(Value::Null, |b| Value::String(api::b64::encode(&b))))\n")
        }
        Some(_) => format!("            to_value({call}?)\n"),
    };
    out.push_str(&body);
    out.push_str("        }\n");
}

pub fn dispatch(idl: &Idl) -> String {
    let mut out = String::from(
        "// @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.\n\nuse super::*;\n\n/// Runs one API call on behalf of a connection.\npub(crate) fn dispatch(state: &mut Handles, method: &str, params: &Value) -> Result<Value, ApiError> {\n    match method {\n",
    );
    for f in &idl.functions {
        dispatch_arm(&mut out, f, None, idl);
    }
    for i in &idl.interfaces {
        for m in &i.methods {
            dispatch_arm(&mut out, m, Some(i), idl);
        }
    }
    out.push_str("        _ => Err(ErrorKind::InvalidArgument.into()),\n    }\n}\n\n/// Every method, so a test can compare it with the JSON-RPC schema.\n#[cfg(test)]\npub(crate) const METHODS: &[&str] = &[\n");
    for f in &idl.functions {
        let _ = writeln!(out, "    {:?},", method_name(f, None));
    }
    for i in &idl.interfaces {
        for m in &i.methods {
            let _ = writeln!(out, "    {:?},", method_name(m, Some(i)));
        }
    }
    out.push_str("];\n");
    out
}

fn all_methods(idl: &Idl) -> Vec<(String, Callable, bool)> {
    let mut methods: Vec<(String, Callable, bool)> =
        idl.functions.iter().map(|f| (method_name(f, None), f.clone(), false)).collect();
    for i in &idl.interfaces {
        for m in &i.methods {
            methods.push((method_name(m, Some(i)), m.clone(), true));
        }
    }
    methods
}

fn bytes_params(c: &Callable) -> Vec<String> {
    c.params
        .iter()
        .filter(|p| p.ty == Ty::Bytes || matches!(&p.ty, Ty::Optional(t) if **t == Ty::Bytes))
        .map(|p| p.name.clone())
        .collect()
}

fn php_function(name: &str) -> String {
    name.replace('.', "_")
}

/// A PHP client: framing, `hello`, base64 for `bytes`, and one method per API call.
pub fn php(idl: &Idl) -> String {
    let mut out = String::from(r#"<?php
// @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.
//
// A client for the qalqond sidecar: length-prefixed JSON-RPC over a Unix socket, or over
// loopback TCP with a per-launch token. It contains framing, hello, base64 and one method
// for each API call, and nothing else. See docs/adr/0004-sidecar-ipc.md.

declare(strict_types=1);

namespace Qalqon;

final class QalqonError extends \RuntimeException
{
    public string $name;

    public function __construct(int $code, string $name, string $message)
    {
        parent::__construct($message, $code);
        $this->name = $name;
    }
}

final class QalqonClient
{
    /** @var resource */
    private $socket;
    private int $nextId = 1;

    /** Connects to a socket path, or to host:port with a token. */
    public function __construct(string $endpoint, ?string $token = null)
    {
        $address = str_contains($endpoint, '/') ? "unix://{$endpoint}" : "tcp://{$endpoint}";
        $socket = stream_socket_client($address, $code, $message, 5.0);
        if ($socket === false) {
            throw new QalqonError(100, 'transportFailed', "cannot reach qalqond: {$message}");
        }
        $this->socket = $socket;
        $params = ['abi' => 0, 'client' => 'php/0.1.0'];
        if ($token !== null) {
            $params['token'] = $token;
        }
        $this->call('qalqond.hello', $params);
    }

    /** Sends one request and waits for its reply. */
    public function call(string $method, array $params = [])
    {
        $id = $this->nextId++;
        $body = json_encode(['jsonrpc' => '2.0', 'id' => $id, 'method' => $method, 'params' => (object) $params], JSON_THROW_ON_ERROR);
        $this->writeAll(pack('N', strlen($body)) . $body);
        $header = $this->readExactly(4);
        $length = unpack('N', $header)[1];
        $reply = json_decode($this->readExactly($length), true, 512, JSON_THROW_ON_ERROR);
        if (isset($reply['error'])) {
            $error = $reply['error'];
            throw new QalqonError((int) $error['code'], (string) ($error['data']['name'] ?? ''), (string) $error['message']);
        }
        return $reply['result'] ?? null;
    }

    private function writeAll(string $bytes): void
    {
        while ($bytes !== '') {
            $written = fwrite($this->socket, $bytes);
            if ($written === false || $written === 0) {
                throw new QalqonError(100, 'transportFailed', 'qalqond went away');
            }
            $bytes = substr($bytes, $written);
        }
    }

    private function readExactly(int $length): string
    {
        $out = '';
        while (strlen($out) < $length) {
            $chunk = fread($this->socket, $length - strlen($out));
            if ($chunk === false || $chunk === '') {
                throw new QalqonError(100, 'transportFailed', 'qalqond went away');
            }
            $out .= $chunk;
        }
        return $out;
    }

"#);
    for (name, c, on_object) in all_methods(idl) {
        let mut params: Vec<String> = Vec::new();
        if on_object {
            params.push("string $handle".into());
        }
        for p in &c.params {
            let optional = matches!(p.ty, Ty::Optional(_));
            params.push(format!("{}${}{}", if optional { "" } else { "" }, p.name, if optional { " = null" } else { "" }));
        }
        let _ = writeln!(out, "    /** {} */", c.doc);
        let _ = writeln!(out, "    public function {}({})\n    {{", php_function(&name), params.join(", "));
        out.push_str("        $params = [");
        if on_object {
            out.push_str("'handle' => $handle");
        }
        for (i, p) in c.params.iter().enumerate() {
            if on_object || i > 0 {
                out.push_str(", ");
            }
            let is_bytes = p.ty == Ty::Bytes;
            let is_optional_bytes = matches!(&p.ty, Ty::Optional(t) if **t == Ty::Bytes);
            if is_bytes {
                let _ = write!(out, "'{0}' => base64_encode(${0})", p.name);
            } else if is_optional_bytes {
                let _ = write!(out, "'{0}' => ${0} === null ? null : base64_encode(${0})", p.name);
            } else {
                let _ = write!(out, "'{0}' => ${0}", p.name);
            }
        }
        out.push_str("];\n");
        let returns_bytes = c.returns.as_ref().is_some_and(|r| *r == Ty::Bytes || matches!(r, Ty::Optional(t) if **t == Ty::Bytes));
        if returns_bytes {
            let _ = writeln!(out, "        $result = $this->call({name:?}, $params);\n        return $result === null ? null : base64_decode($result, true);");
        } else {
            let _ = writeln!(out, "        return $this->call({name:?}, $params);");
        }
        out.push_str("    }\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n}\n");
    out
}

/// A Ruby client, with the same shape as the PHP one.
pub fn ruby(idl: &Idl) -> String {
    let mut out = String::from(r#"# @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.
#
# A client for the qalqond sidecar. See docs/adr/0004-sidecar-ipc.md.

require 'base64'
require 'json'
require 'socket'

module Qalqon
  class Error < StandardError
    attr_reader :code, :name

    def initialize(code, name, message)
      super(message)
      @code = code
      @name = name
    end
  end

  class Client
    def initialize(endpoint, token: nil)
      @socket = endpoint.include?('/') ? UNIXSocket.new(endpoint) : TCPSocket.new(*endpoint.split(':'))
      @next_id = 1
      params = { abi: 0, client: 'ruby/0.1.0' }
      params[:token] = token if token
      call('qalqond.hello', params)
    end

    def call(method, params = {})
      id = @next_id
      @next_id += 1
      body = JSON.generate(jsonrpc: '2.0', id: id, method: method, params: params)
      @socket.write([body.bytesize].pack('N') + body)
      header = @socket.read(4)
      raise Error.new(100, 'transportFailed', 'qalqond went away') if header.nil?
      reply = JSON.parse(@socket.read(header.unpack1('N')))
      if (error = reply['error'])
        raise Error.new(error['code'], error.dig('data', 'name'), error['message'])
      end
      reply['result']
    end

"#);
    for (name, c, on_object) in all_methods(idl) {
        let ruby_name = snake(&name.replace('.', "_"));
        let mut params: Vec<String> = Vec::new();
        if on_object {
            params.push("handle".into());
        }
        for p in &c.params {
            params.push(if matches!(p.ty, Ty::Optional(_)) { format!("{}: nil", snake(&p.name)) } else { snake(&p.name) });
        }
        let _ = writeln!(out, "    # {}", c.doc);
        let _ = writeln!(out, "    def {ruby_name}({})", params.join(", "));
        let mut entries: Vec<String> = Vec::new();
        if on_object {
            entries.push("handle: handle".into());
        }
        for p in &c.params {
            let value = if bytes_params(&c).contains(&p.name) {
                if matches!(p.ty, Ty::Optional(_)) {
                    format!("{0} && Base64.strict_encode64({0})", snake(&p.name))
                } else {
                    format!("Base64.strict_encode64({})", snake(&p.name))
                }
            } else {
                snake(&p.name)
            };
            entries.push(format!("{}: {value}", p.name));
        }
        let returns_bytes = c.returns.as_ref().is_some_and(|r| *r == Ty::Bytes || matches!(r, Ty::Optional(t) if **t == Ty::Bytes));
        if returns_bytes {
            let _ = writeln!(out, "      result = call({name:?}, {{ {} }})\n      result && Base64.strict_decode64(result)", entries.join(", "));
        } else {
            let _ = writeln!(out, "      call({name:?}, {{ {} }})", entries.join(", "));
        }
        out.push_str("    end\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n  end\nend\n");
    out
}

/// An Elixir client: one module over `:gen_tcp`, with `Jason` for JSON.
pub fn elixir(idl: &Idl) -> String {
    let mut out = String::from(r#"# @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.
#
# A client for the qalqond sidecar. See docs/adr/0004-sidecar-ipc.md. It needs Jason.

defmodule Qalqon.Client do
  @moduledoc "Length-prefixed JSON-RPC to qalqond over a Unix socket or loopback TCP."

  defstruct [:socket]

  def connect(endpoint, token \\ nil) do
    {address, port} =
      if String.contains?(endpoint, "/") do
        {{:local, String.to_charlist(endpoint)}, 0}
      else
        [host, port] = String.split(endpoint, ":")
        {String.to_charlist(host), String.to_integer(port)}
      end

    {:ok, socket} = :gen_tcp.connect(address, port, [:binary, active: false, packet: 4])
    client = %__MODULE__{socket: socket}
    params = %{abi: 0, client: "elixir/0.1.0"}
    params = if token, do: Map.put(params, :token, token), else: params
    {:ok, _} = call(client, "qalqond.hello", params)
    client
  end

  def call(%__MODULE__{socket: socket}, method, params \\ %{}) do
    body = Jason.encode!(%{jsonrpc: "2.0", id: 1, method: method, params: params})
    :ok = :gen_tcp.send(socket, body)
    {:ok, reply} = :gen_tcp.recv(socket, 0)

    case Jason.decode!(reply) do
      %{"error" => error} -> {:error, error["code"], get_in(error, ["data", "name"]), error["message"]}
      %{"result" => result} -> {:ok, result}
    end
  end

"#);
    for (name, c, on_object) in all_methods(idl) {
        let fun = snake(&name.replace('.', "_"));
        let mut params = vec!["client".to_string()];
        if on_object {
            params.push("handle".into());
        }
        for p in &c.params {
            params.push(if matches!(p.ty, Ty::Optional(_)) { format!("{} \\\\ nil", snake(&p.name)) } else { snake(&p.name) });
        }
        let _ = writeln!(out, "  @doc {:?}", c.doc);
        let _ = writeln!(out, "  def {fun}({}) do", params.join(", "));
        let mut entries: Vec<String> = Vec::new();
        if on_object {
            entries.push("handle: handle".into());
        }
        for p in &c.params {
            let value = if bytes_params(&c).contains(&p.name) {
                if matches!(p.ty, Ty::Optional(_)) {
                    format!("{0} && Base.encode64({0})", snake(&p.name))
                } else {
                    format!("Base.encode64({})", snake(&p.name))
                }
            } else {
                snake(&p.name)
            };
            entries.push(format!("{}: {value}", p.name));
        }
        let _ = writeln!(out, "    call(client, {name:?}, %{{{}}})", entries.join(", "));
        out.push_str("  end\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push_str("\nend\n");
    out
}

/// A shell client. `curl` cannot speak the framing, so this talks to a `qalqond client`
/// co-process, which turns JSON lines into framed requests over one connection.
pub fn shell(idl: &Idl) -> String {
    let mut out = String::from(r#"#!/usr/bin/env bash
# @generated by tools/idlgen from core/idl/qalqon.api.yaml. Do not edit.
#
# Source this file, then call `qalqon_start <socket>`. Each function takes JSON values as
# arguments and prints the result as JSON. It needs bash 4, jq and qalqond on PATH.
# See docs/adr/0004-sidecar-ipc.md.

qalqon_start() {
  coproc QALQOND { qalqond client "$1"; }
  QALQON_NEXT_ID=1
}

qalqon_stop() {
  if [ -n "${QALQOND_PID:-}" ]; then
    kill "$QALQOND_PID" 2>/dev/null
    wait "$QALQOND_PID" 2>/dev/null
  fi
  return 0
}

# qalqon_call <method> <params-json>
qalqon_call() {
  local id=$QALQON_NEXT_ID reply
  QALQON_NEXT_ID=$((id + 1))
  jq -cn --argjson id "$id" --arg method "$1" --argjson params "$2" \
    '{jsonrpc: "2.0", id: $id, method: $method, params: $params}' >&"${QALQOND[1]}"
  IFS= read -r reply <&"${QALQOND[0]}" || { echo "qalqond went away" >&2; return 100; }
  if [ "$(jq -r 'has("error")' <<<"$reply")" = true ]; then
    jq -c '.error' <<<"$reply" >&2
    return "$(jq -r '.error.code % 256' <<<"$reply")"
  fi
  jq -c '.result' <<<"$reply"
}

"#);
    for (name, c, on_object) in all_methods(idl) {
        let fun = format!("qalqon_{}", snake(&name.replace('.', "_")));
        let mut names: Vec<String> = Vec::new();
        if on_object {
            names.push("handle".into());
        }
        names.extend(c.params.iter().map(|p| p.name.clone()));
        let _ = writeln!(out, "# {}", c.doc);
        if !names.is_empty() {
            let _ = writeln!(out, "# Arguments: {}. Each is JSON, so a string needs its quotes.", names.join(", "));
        }
        let mut jq_args = String::new();
        let mut object = Vec::new();
        for (i, n) in names.iter().enumerate() {
            let _ = write!(jq_args, " --argjson a{i} \"${{{}:-null}}\"", i + 1);
            object.push(format!("{n}: $a{i}"));
        }
        let _ = writeln!(out, "{fun}() {{\n  qalqon_call {name:?} \"$(jq -cn{jq_args} '{{{}}}')\"\n}}\n", object.join(", "));
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
